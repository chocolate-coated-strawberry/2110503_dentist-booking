const variables = new Map();
[...A.variable, ...B.variable].forEach((v) => variables.set(v.key, { key: v.key, value: '' }));
variables.set('URL', B.variable.find((v) => v.key === 'URL'));
variables.delete('TOKEN_USER');

const demo = {
    info: {
        name: 'dentist-booking-demo',
        description: 'Presentation demo: steps 1-12 in the course order, plus extra credits. '
            + 'Generated by postman/build-demo.js from collections A and B; do not edit by hand.',
        schema: B.info.schema
    },
    item: STEPS.map(([name, list]) => ({ name, item: list.map(([src, req]) => pick(src, req)) })),
    event: B.event,
    variable: [...variables.values()]
};

const out = path.join(__dirname, 'dentist-booking-demo.postman_collection.json');
fs.writeFileSync(out, JSON.stringify(demo, null, 2) + '\n');
console.log(`Wrote ${out}`);
