// Builds the presentation demo collection: the requests of A and B, regrouped into the
// course's step order (1 Register ... 12 Admin delete). A and B stay the source of truth.
// npm test rebuilds it first (pretest), so a test run never uses a stale demo.
// After editing A or B, commit the regenerated demo file too.
const fs = require('fs');
const path = require('path');

const load = (name) => require(`./${name}.postman_collection.json`);
const A = load('dentist-booking-A');
const B = load('dentist-booking-B');

// name -> request item, across all folders
const index = (col) => {
    const map = new Map();
    const walk = (items) => items.forEach((i) => (i.item ? walk(i.item) : map.set(i.name, i)));
    walk(col.item);
    return map;
};
const reqs = { A: index(A), B: index(B) };

const pick = (src, name) => {
    const item = reqs[src].get(name);
    if (!item) throw new Error(`Request "${name}" not found in collection ${src}`);
    // A's single user is user2; reuse B's user2 token so A's own user login is not needed
    const json = JSON.stringify(item);
    return JSON.parse(src === 'A' ? json.replaceAll('{{TOKEN_USER}}', '{{TOKEN_USER2}}') : json);
};

